"""Rebuilds quartz/components/data/l3excellence.ts, the index behind the random
L3 excellence question picker (content/Past-Papers/Random-L3-Excellence.md).

For each page of the three collated excellence PDFs this works out the vertical
slice that actually holds the question, by rendering the page in greyscale and
throwing away the ruled answer lines and the "91577 2013" footer label, so the
site can draw the question without a page of blank lines under it.
Pages whose second line is "Continued" are folded into the question before them.

Run it again whenever those PDFs change (a new year, say):

    python3 -m venv /tmp/l3venv && /tmp/l3venv/bin/pip install pymupdf
    /tmp/l3venv/bin/python scripts/build-l3-excellence-index.py
    npx prettier --write quartz/components/data/l3excellence.ts
"""
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "content" / "Past-Papers" / "L3"
TOPICS = [
    ("comp", "91577", "Complex Numbers", "Complex-Numbers", "91577-excellence(2013~2025).pdf"),
    ("diff", "91578", "Differentiation", "Differentiation", "91578-excellence(2013~2025).pdf"),
    ("inte", "91579", "Integration", "Integration", "91579-excellence(2013~2025).pdf"),
]

SCAN = 0.5          # render scale used for the ink scan
FOOTER = 0.925      # everything below this is the page label
RULE_X0, RULE_X1 = 225, 1256   # the ruled answer lines span exactly this
PAD = 0.012         # breathing room kept above and below, as a page fraction


def slice_of(page):
    """Top and bottom of the question on this page, as fractions of the page."""
    pm = page.get_pixmap(matrix=pymupdf.Matrix(SCAN, SCAN), colorspace=pymupdf.csGRAY)
    w, h, stride, buf = pm.width, pm.height, pm.stride, pm.samples
    rx0, rx1 = int(RULE_X0 * SCAN), int(RULE_X1 * SCAN)
    rule_len = rx1 - rx0
    kinds = []
    for y in range(int(h * FOOTER)):
        row = buf[y * stride : y * stride + w]
        dark = [x for x in range(w) if row[x] < 200]
        if not dark:
            kinds.append(None)
            continue
        is_rule = len(dark) > rule_len * 0.5 and dark[0] >= rx0 - 4 and dark[-1] <= rx1 + 4
        kinds.append("rule" if is_rule else "ink")
    top = next((y for y, k in enumerate(kinds) if k == "ink"), 0)
    bottom = next((y for y in range(len(kinds) - 1, -1, -1) if kinds[y] == "ink"), h - 1)
    return (max(0.0, top / h - PAD), min(1.0, (bottom + 1) / h + PAD))


out = []
for key, std, name, folder, fname in TOPICS:
    doc = pymupdf.open(BASE / folder / fname)
    questions = []
    for i, page in enumerate(doc):
        lines = [l.strip() for l in page.get_text().strip().split("\n")]
        year = int(lines[0].split()[1])
        top, bottom = slice_of(page)
        part = {"page": i + 1, "top": round(top, 4), "bottom": round(bottom, 4)}
        if len(lines) > 1 and lines[1].lower().startswith("continued") and questions:
            questions[-1]["parts"].append(part)
        else:
            questions.append({"year": year, "parts": [part]})
    # number the questions inside each year, in the order the paper has them
    seen = {}
    for q in questions:
        seen[q["year"]] = seen.get(q["year"], 0) + 1
        q["n"] = seen[q["year"]]
    out.append(
        {
            "key": key,
            "standard": std,
            "name": name,
            "file": f"/Past-Papers/L3/{folder}/{fname}",
            "answers": f"/Past-Papers/L3/{folder}/Answers/",
            "paper": f"/Past-Papers/L3/{folder}/Assessment/",
            "questions": questions,
        }
    )
    print(key, len(doc), "pages ->", len(questions), "questions")


# ---- also write the TypeScript data module the site bundles ----
ts = ['''// Generated by scripts/build-l3-excellence-index.py — do not edit by hand.
// One entry per excellence question in the three collated L3 PDFs. `parts` holds
// [page, top, bottom] for each page the question covers, where top/bottom are the
// slice of the page that has the question on it (the rest is ruled answer space).

export type QuestionPart = [page: number, top: number, bottom: number]

export type Question = {
  year: number
  n: number // which excellence question it is in that year's paper (1-3)
  parts: QuestionPart[]
}

export type Topic = {
  key: string
  standard: string
  name: string
  short: string
  file: string // collated excellence PDF
  answers: string // folder of answer schedules, one PDF per year
  paper: string // folder of full papers, one PDF per year
  questions: Question[]
}

export const TOPICS: Topic[] = [''']
SHORT = {"comp": "Comp", "diff": "Diff", "inte": "Inte"}
for t in out:
    ts.append("  {")
    ts.append(f'    key: "{t["key"]}",')
    ts.append(f'    standard: "{t["standard"]}",')
    ts.append(f'    name: "{t["name"]}",')
    ts.append(f'    short: "{SHORT[t["key"]]}",')
    ts.append(f'    file: "{t["file"]}",')
    ts.append(f'    answers: "{t["answers"]}",')
    ts.append(f'    paper: "{t["paper"]}",')
    ts.append("    questions: [")
    for q in t["questions"]:
        parts = ", ".join(f'[{p["page"]}, {p["top"]}, {p["bottom"]}]' for p in q["parts"])
        ts.append(f'      {{ year: {q["year"]}, n: {q["n"]}, parts: [{parts}] }},')
    ts.append("    ],")
    ts.append("  },")
ts.append("]\n")
target = ROOT / "quartz" / "components" / "data" / "l3excellence.ts"
target.write_text("\n".join(ts))
print("wrote", target)
print("now run: npx prettier --write quartz/components/data/l3excellence.ts")
